// Helper functions
export function getPatternById(id: string): BreathPattern | undefined {
  return PATTERNS.find((p) => p.id === id);
}

export function getPatternsByCategory(category: string): BreathPattern[] {
  return PATTERNS.filter((p) => p.category === category);
}

export function getPatternsForLevel(level: number): BreathPattern[] {
  return PATTERNS.filter((p) => p.requiredLevel <= level);
}

export function getCategoryLabel(category: string): string {
  const labels: Record<string, string> = {
    parasympathetic: 'Calm',
    sympathetic: 'Energy',
    clinical: 'Clinical',
    transformative: 'Transform',
  };
  return labels[category] || category;
}

